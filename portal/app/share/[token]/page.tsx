import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";

import Logo from "@/assets/logo/logo";
import { Markdown } from "@/components/ai/markdown";
import { Button } from "@/components/ui/button";
import { readSharedConversation } from "@/lib/chat/share-read";

export const dynamic = "force-dynamic";

/**
 * /share/[token] — the public view of a shared conversation (audit #11).
 *
 * THIS PAGE HAS NO SESSION. Every visibility rule is re-derived from the
 * token by `readSharedConversation`, which applies revoked, expired,
 * temporary, archived and partial-share gates in one place. The page itself
 * only renders what it is handed, so a mistake here cannot widen access.
 *
 * DELIBERATELY MINIMAL. No sidebar, no composer, no cost figures, no
 * reasoning panel: a reader sees the conversation and a single route into
 * the product. Cost and deliberation are the owner's, not a stranger's.
 *
 * `noindex` because a shared link is a private grant, not a publication —
 * the README's own wording. Search engines indexing a share would turn
 * "share with one person" into "publish to the web".
 */
export const metadata: Metadata = {
  title: "Shared conversation",
  robots: { index: false, follow: false },
};

export default async function SharedConversationPage({
  params,
}: {
  params: Promise<{ token: string }>;
}) {
  const { token } = await params;
  const conversation = await readSharedConversation(token);
  if (!conversation) notFound();

  return (
    <div className="min-h-dvh bg-background">
      <header className="sticky top-0 z-10 flex h-14 items-center justify-between border-b border-border/60 bg-background/80 px-4 backdrop-blur-xl">
        <Link href="/" aria-label="Zaino AI">
          <Logo wordmark size="sm" />
        </Link>
        <Button size="sm" variant="outline" nativeButton={false} render={<Link href="/chat" />}>
          Start your own chat
        </Button>
      </header>

      <main className="mx-auto w-full max-w-3xl px-4 py-8">
        <p className="mb-6 text-xs text-muted-foreground">
          Shared conversation · read-only. You are seeing one chat, not an account.
        </p>
        <h1 className="mb-8 text-2xl font-semibold tracking-tight text-balance">
          {conversation.title}
        </h1>

        <div className="flex flex-col gap-8">
          {conversation.messages.map((message) =>
            message.role === "user" ? (
              <div key={message.id} className="flex w-full flex-col items-end">
                <div className="max-w-[95%] rounded-lg bg-secondary px-4 py-3 text-sm leading-relaxed whitespace-pre-wrap">
                  {message.content}
                </div>
              </div>
            ) : (
              /* A shared answer is the same document it was in the app:
                 headings, lists, tables, code fences, maths. Rendered as
                 pre-wrapped text it arrived as a wall of markdown source,
                 which is not what the user chose to publish. Streamdown
                 parses to a React tree and hardens raw HTML, so model
                 output is safe here too. */
              <div key={message.id} className="w-full">
                <Markdown>{message.content}</Markdown>
              </div>
            ),
          )}
        </div>

        {conversation.messages.length === 0 && (
          <p className="py-12 text-center text-sm text-muted-foreground">
            This conversation has no messages to show.
          </p>
        )}

        <footer className="mt-12 border-t border-border/60 pt-6">
          <p className="text-xs text-muted-foreground">
            Answers are generated by an AI model and may be wrong. Verify anything that
            matters.
          </p>
        </footer>
      </main>
    </div>
  );
}
